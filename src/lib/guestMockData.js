// 5. 대시보드 계좌별 보유현황 (계좌별 그룹화)
export const GUEST_HOLDINGS_BY_ACCOUNT = GUEST_HOLDINGS.reduce((acc, h) => {
  const accName = h.account_name || '기타';
  if (!acc[accName]) acc[accName] = [];
  acc[accName].push({ ...h });
  return acc;
}, {});

// 각 계좌 내 정렬 (통화 -> 평가금액순)
Object.keys(GUEST_HOLDINGS_BY_ACCOUNT).forEach(accName => {
  GUEST_HOLDINGS_BY_ACCOUNT[accName].sort((a, b) => {
    if (a.currency_order !== b.currency_order) return a.currency_order - b.currency_order;
    return b.evaluationAmountKRW - a.evaluationAmountKRW;
  });
});

